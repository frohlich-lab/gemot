"""Deterministic LaTeX inputs for the manuscript.

The paper's appendix is assembled by three writers with three different policies, and this
module owns exactly one of them: the **reproducible** half. It reads the repository — each
example's ``problem/reference.json``, the materialized PEtab tables when they exist, the
curated ``paper/findings.toml`` and exported sweep observations — and emits LaTeX that is
overwritten on every run and verified by :mod:`tests.test_paper_inputs` to regenerate byte-identically.

The other two writers are prose: humans editing in Overleaf, and an agent drafting appendix
narrative from the sweep logs. Neither may write into :func:`generated_dir`, and nothing here
may write outside it. The boundary is what keeps an Overleaf round-trip conflict-free — see
[paper/README.md](../../paper/README.md) for the full contract.

Numbers cross into prose as macros, never as literals. A drafted sentence says
``\\sneydBasinGap``, so a stale or invented figure cannot survive: the value has one
definition, here, carrying the sweep it came from.
"""

from __future__ import annotations

import csv
import hashlib
import importlib.util
import io
import json
import math
import re
import statistics
import subprocess
import tomllib
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from petab_harness.paths import BENCHMARK_EXAMPLES, examples_root, repo_root

#: Header stamped on every emitted file. The manuscript's coauthors edit in Overleaf, where a
#: generated file looks exactly like a hand-written one; without this they cannot tell which
#: of their edits the next sync will discard.
DO_NOT_EDIT = "% DO NOT EDIT -- regenerated by petab_harness.paper. Edits here are discarded."

#: Outputs that are a function of the checkout rather than of its content, so they change on
#: every commit and cannot be compared for byte-identity. Everything else must be
#: reproducible -- see tests/test_paper_inputs.py.
VOLATILE_OUTPUTS = frozenset({"provenance.tex"})

# Stored units match the figure's observations. Token macros use tokens rather than millions;
# both time series use hours. Medians are calculated before any logarithmic transformation.
SWEEP_METRICS = (
    ("delta_bic", "DeltaBIC", 1, "BIC"),
    ("delta_nll", "DeltaNLLH", 1, "negative log likelihood"),
    ("delta_k", "DeltaParameters", 1, "parameters"),
    ("delta_states", "DeltaStates", 1, "states"),
    ("n_fits", "Fits", 1, "fits per run"),
    ("tokens", "LLMTokens", 1, "tokens per run"),
    ("wall_h", "WallHours", 1, "elapsed hours per run"),
    ("cpu_h", "CPUHours", 1, "CPU hours per run, all workers"),
)


def sweep_data_path() -> Path:
    """Exact plotted observations exported by slurm/sweep_panels.py --paper-data."""
    return repo_root() / "paper" / "sweep_data.json"


def read_sweep_data() -> dict | None:
    """Read the portable sweep input; no cluster access or refits are needed to rebuild."""
    path = sweep_data_path()
    if not path.is_file():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1:
        raise ValueError(f"{path}: unsupported sweep data schema")
    runs, examples = data["runs"], data["example_order"]
    if not runs or len({r["task"] for r in runs}) != len(runs):
        raise ValueError(f"{path}: sweep observations must have unique task IDs")
    if len(examples) != len(set(examples)) or set(examples) != {r["example"] for r in runs}:
        raise ValueError(f"{path}: example order must cover every observed example once")
    if not data.get("jobs") or not data.get("source") or data.get("per_example", 0) < 1:
        raise ValueError(f"{path}: missing sweep provenance or selection size")
    for example, counts in data["counts"].items():
        if "modalities" in counts:
            modalities = counts["modalities"]
            if (not isinstance(modalities, list)
                    or any(not isinstance(m, str) or not m for m in modalities)
                    or counts.get("n_modalities") != len(modalities)
                    or len(set(modalities)) != len(modalities)):
                raise ValueError(f"{path}: inconsistent modality count for {example}")
    return data


def sweep_statistics(data: dict) -> dict[str, dict]:
    """Per-example medians over the same finite observations as the boxplots, including zero."""
    summary = {}
    metrics = list(SWEEP_METRICS)
    if any(r.get("cost") is not None for r in data["runs"]):
        metrics.append(("cost", "LLMCostUSD", 1, "USD per run"))
    for ex in data["example_order"]:
        runs = [r for r in data["runs"] if r["example"] == ex]
        row = {"run_count": len(runs), "counts": data["counts"].get(ex, {}), "metrics": {}}
        for key, suffix, factor, unit in metrics:
            values = [float(r[key]) * factor for r in runs
                      if r.get(key) is not None and math.isfinite(float(r[key]))]
            row["metrics"][suffix] = {
                "median": statistics.median(values) if values else None,
                "n": len(values), "unit": unit,
            }
        summary[ex] = row
    return summary


def _sweep_number(value) -> str:
    """Plain numeric macros, at most six decimal places; missing is explicit, never zero."""
    if value is None:
        return r"\textnormal{n/a}"
    text = f"{value:.6f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def sweep_macros(data: dict) -> dict[str, str]:
    """One namespace for this figure, distinct from older campaigns in findings.toml."""
    macros = {"sweepFigureExampleCount": str(len(data["example_order"])),
              "sweepFigureRunCount": str(len(data["runs"])),
              "sweepFigureRunsPerExample": str(data["per_example"])}
    for ex, row in sweep_statistics(data).items():
        if not re.fullmatch(r"[a-z]+(?:_[a-z]+)*", ex):
            raise ValueError(f"invalid sweep example name: {ex!r}")
        prefix = "sweepFigure" + "".join(word.capitalize() for word in ex.split("_"))
        if prefix + "RunCount" in macros:
            raise ValueError(f"duplicate sweep macro prefix: {prefix}")
        macros[prefix + "RunCount"] = str(row["run_count"])
        for key, suffix in (("n_observables", "Observables"), ("n_datapoints", "Datapoints"),
                            ("n_conditions", "Conditions"), ("n_modalities", "Modalities")):
            macros[prefix + suffix] = _sweep_number(row["counts"].get(key))
        for suffix, metric in row["metrics"].items():
            macros[prefix + "Median" + suffix] = _sweep_number(metric["median"])
            macros[prefix + suffix + "N"] = str(metric["n"])
    return macros


def render_sweep_csv(data: dict) -> str:
    """Unrounded median values and available sample sizes, in the same example order."""
    rows = []
    for ex, summary in sweep_statistics(data).items():
        row = {"example": ex, "n_runs": summary["run_count"],
               **{key: summary["counts"].get(key)
                  for key in ("n_observables", "n_datapoints", "n_conditions", "n_modalities")}}
        for suffix, metric in summary["metrics"].items():
            row["median_" + suffix] = metric["median"]
            row["n_" + suffix] = metric["n"]
        rows.append(row)
    output = io.StringIO(newline="")
    writer = csv.DictWriter(output, fieldnames=list(rows[0]), lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return output.getvalue()


@dataclass(frozen=True)
class ExampleRow:
    """One roster-table row: what the benchmark withheld, and the bar it must clear."""

    name: str
    reference_k: int | None
    reference_n: int | None
    reference_nll: float | None
    n_observables: int | None
    n_conditions: int | None


def generated_dir() -> Path:
    """The only directory this module writes to."""
    return repo_root() / "paper" / "generated"


def findings_path() -> Path:
    """The curated numbers file.

    Values measured by a sweep but recorded only in prose (``FINDINGS.md``,
    ``BENCHMARK_NOTES.md``) cannot be recomputed from a checkout, so they are transcribed once,
    by hand, each carrying the job ids and date that produced it. Transcribing them here rather
    than into the manuscript is what makes the provenance travel with the number.
    """
    return repo_root() / "paper" / "findings.toml"


def git_sha() -> str:
    """The checkout's sha, with a ``+dirty`` suffix when the tree has uncommitted changes.

    Matches the convention ``result.json`` and the Phoenix run span already use, so a figure
    and the run behind it can be lined up by string equality.
    """
    root = repo_root()
    sha = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
        capture_output=True, text=True, check=False,
    ).stdout.strip() or "unknown"
    dirty = subprocess.run(
        ["git", "-C", str(root), "status", "--porcelain"],
        capture_output=True, text=True, check=False,
    ).stdout.strip()
    return f"{sha}+dirty" if dirty else sha


def git_commit_date() -> str:
    """HEAD's commit date in UTC, or ``unknown`` without git metadata.

    The wall clock is not an input: rebuilding an unchanged checkout on a later day must
    not create a new manuscript diff. The Unix timestamp also avoids the committer's local
    timezone changing the date we report.
    """
    result = subprocess.run(
        ["git", "-C", str(repo_root()), "show", "-s", "--format=%ct", "HEAD"],
        capture_output=True, text=True, check=False,
    )
    if result.returncode or not result.stdout.strip():
        return "unknown"
    return datetime.fromtimestamp(int(result.stdout.strip()), UTC).date().isoformat()


def _count_rows(path: Path) -> int | None:
    if not path.is_file():
        return None
    lines = [ln for ln in path.read_text().splitlines() if ln.strip()]
    return max(len(lines) - 1, 0)


def read_roster() -> list[ExampleRow]:
    """Collect one row per PUBLISHED example.

    The synthetic scenarios are excluded: they simulate their own data from a withheld truth,
    which makes them a harness self-test rather than evidence about real biological data, and
    the paper reports only the published problems.

    ``reference.json`` is committed for all of them, so the bar is always readable. The PEtab
    tables are NOT: the benchmark examples are materialized by ``examples/setup.py`` and
    gitignored, so observable and condition counts are ``None`` in a fresh checkout. They are
    reported as such rather than guessed.
    """
    rows: list[ExampleRow] = []
    for name in BENCHMARK_EXAMPLES:
        problem = examples_root() / name / "problem"
        ref: dict[str, object] = {}
        ref_path = problem / "reference.json"
        if ref_path.is_file():
            ref = json.loads(ref_path.read_text())
        rows.append(ExampleRow(
            name=name,
            reference_k=ref.get("k"),
            reference_n=ref.get("n"),
            reference_nll=ref.get("nll"),
            n_observables=_count_rows(problem / "observables.tsv"),
            n_conditions=_count_rows(problem / "conditions.tsv"),
        ))
    return rows


def _cell(value: object) -> str:
    if value is None:
        return r"\needsmaterialize"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def render_roster(rows: list[ExampleRow]) -> str:
    """The roster longtable (Table 1)."""
    out = [
        DO_NOT_EDIT,
        r"% Columns marked \needsmaterialize require `python examples/setup.py` first.",
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r"Example & $k_\mathrm{ref}$ & $n$ & $\mathrm{nll}_\mathrm{ref}$ & Obs. & Cond. \\",
        r"\midrule",
    ]
    for r in rows:
        out.append(
            f"{r.name.replace('_', r'\_')} & {_cell(r.reference_k)} & "
            f"{_cell(r.reference_n)} & {_cell(r.reference_nll)} & "
            f"{_cell(r.n_observables)} & {_cell(r.n_conditions)} \\\\"
        )
    out += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(out)


def render_values(rows: list[ExampleRow], findings: dict[str, dict[str, object]],
                  sweep: dict | None = None) -> str:
    """Every number the prose may cite, as a macro.

    Three sources share one file: counts derived from the checkout, sweep-figure medians and
    curated historical values. A reader of the manuscript cannot tell them apart, and should
    not have to -- each carries its provenance as a comment on the definition.
    """
    out = [DO_NOT_EDIT, "", "% -- derived from the checkout --"]
    out.append(rf"\newcommand{{\nExamples}}{{{len(rows)}}}")
    out.append("")
    derived = sweep_macros(sweep) if sweep else {}
    if sweep:
        fingerprint = hashlib.sha256(json.dumps(sweep, sort_keys=True).encode()).hexdigest()
        out += ["% -- medians of the exact sweep-figure observations: paper/sweep_data.json --",
                "% Jobs: " + ", ".join(sweep["jobs"]),
                "% Data SHA256 (canonical JSON): " + fingerprint,
                "% Selection: latest started runs per example; each metric omits missing values.",
                "% Medians use original units, before log transforms; N gives available runs.",
                "% Delta values are fitted minus reference; LLMTokens is tokens, not millions.",
                "% WallHours is full-task elapsed hours; CPUHours sums measured CPU over workers.",
                "% Numeric macros use up to six decimal places; sweep_medians.csv is unrounded."]
        for macro, value in derived.items():
            out.append(rf"\newcommand{{\{macro}}}{{{value}}}")
        out.append("")
    out.append("% -- transcribed from sweep logs, see paper/findings.toml --")
    macros = {"nExamples", "repoSha", "generatedOn", "nUnmaterialized", *derived}
    for key in sorted(findings):
        entry = findings[key]
        macro = entry.get("macro")
        if not isinstance(macro, str) or re.fullmatch(r"[A-Za-z]+", macro) is None:
            raise ValueError(f"{key}: macro must be an explicit name containing only ASCII letters")
        if macro in macros:
            raise ValueError(f"{key}: macro {macro!r} is already defined")
        macros.add(macro)
        out.append(f"% {entry.get('source', '?')} :: {entry.get('provenance', 'UNRECORDED')}")
        out.append(rf"\newcommand{{\{macro}}}{{{entry.get('value', '')}}}")
    out.append("")
    return "\n".join(out)


def render_provenance(rows: list[ExampleRow]) -> str:
    """What a reviewer needs to re-derive the generated half.

    ``generatedOn`` names HEAD's UTC commit date, not the time this renderer was run.
    """
    missing = [r.name for r in rows if r.n_observables is None]
    out = [
        DO_NOT_EDIT,
        "",
        rf"\newcommand{{\repoSha}}{{{git_sha()}}}",
        "% generatedOn is HEAD's commit date in UTC, not the generation time.",
        rf"\newcommand{{\generatedOn}}{{{git_commit_date()}}}",
        rf"\newcommand{{\nUnmaterialized}}{{{len(missing)}}}",
        "",
    ]
    if missing:
        out.append(f"% not materialized in this checkout: {', '.join(missing)}")
        out.append("")
    return "\n".join(out)


def build(out_dir: Path | None = None) -> dict[Path, str]:
    """Write generated text/data inputs; build_figures handles PDFs. Return paths to content."""
    target = out_dir or generated_dir()
    target.mkdir(parents=True, exist_ok=True)
    rows = read_roster()
    findings: dict[str, dict[str, object]] = {}
    if findings_path().is_file():
        findings = tomllib.loads(findings_path().read_text())
    sweep = read_sweep_data()
    files = {
        target / "roster.tex": render_roster(rows),
        target / "values.tex": render_values(rows, findings, sweep),
        target / "provenance.tex": render_provenance(rows),
    }
    if sweep:
        files.update({
            target / "sweep_medians.csv": render_sweep_csv(sweep),
            target / "sweep_data.json": json.dumps(sweep, indent=2, ensure_ascii=False,
                                                    allow_nan=False) + "\n",
            target / "sweep_figure.tex": "\n".join([
                DO_NOT_EDIT,
                "% Requires graphicx; input this inside the manuscript's figure environment.",
                r"\includegraphics[width=\linewidth]{paper/generated/sweep_panels.pdf}", "",
            ]),
        })
    for path, content in files.items():
        path.write_text(content, encoding="utf-8")
    return files


def build_figures(out_dir: Path | None = None) -> list[Path]:
    """Render the sweep's vector PDF from the same portable input as the median macros.

    Kept separate from the text build so numeric inputs remain usable without Matplotlib.
    The repo's existing sweep renderer owns the layout; no plotting logic is duplicated here.
    """
    data = read_sweep_data()
    if data is None:
        return []
    script = repo_root() / "slurm" / "sweep_panels.py"
    spec = importlib.util.spec_from_file_location("_paper_sweep_panels", script)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    target = out_dir or generated_dir()
    target.mkdir(parents=True, exist_ok=True)
    path = target / "sweep_panels.pdf"
    module.render(data["runs"], str(path), data["title"], data["per_example"],
                  data["counts"], data["labels"])
    return [path]
