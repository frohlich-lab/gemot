"""Deterministic LaTeX inputs for the manuscript.

The paper's appendix is assembled by three writers with three different policies, and this
module owns exactly one of them: the **reproducible** half. It reads the repository — each
example's ``problem/reference.json``, the materialized PEtab tables when they exist, and the
curated ``paper/findings.toml`` — and emits LaTeX that is overwritten on every run and
verified by :mod:`tests.test_paper_inputs` to regenerate byte-identically.

The other two writers are prose: humans editing in Overleaf, and an agent drafting appendix
narrative from the sweep logs. Neither may write into :func:`generated_dir`, and nothing here
may write outside it. The boundary is what keeps an Overleaf round-trip conflict-free — see
[paper/README.md](../../paper/README.md) for the full contract.

Numbers cross into prose as macros, never as literals. A drafted sentence says
``\\sneydBasinGap``, so a stale or invented figure cannot survive: the value has one
definition, here, carrying the sweep it came from.
"""

from __future__ import annotations

import json
import re
import subprocess
import tomllib
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from petab_harness.paths import BENCHMARK_EXAMPLES, examples_root, repo_root

#: Header stamped on every emitted file. The manuscript's coauthors edit in Overleaf, where a
#: generated file looks exactly like a hand-written one; without this they cannot tell which
#: of their edits the next sync will discard.
DO_NOT_EDIT = "% DO NOT EDIT -- regenerated by petab_harness.paper. Edits here are discarded."

#: Outputs that are a function of the checkout rather than of its content, so they change on
#: every commit and cannot be compared for byte-identity. Everything else must be
#: reproducible -- see tests/test_paper_inputs.py.
VOLATILE_OUTPUTS = frozenset({"provenance.tex"})


@dataclass(frozen=True)
class ExampleRow:
    """One roster-table row: what the benchmark withheld, and the bar it must clear."""

    name: str
    reference_k: int | None
    reference_n: int | None
    reference_nll: float | None
    n_observables: int | None
    n_conditions: int | None


def generated_dir() -> Path:
    """The only directory this module writes to."""
    return repo_root() / "paper" / "generated"


def findings_path() -> Path:
    """The curated numbers file.

    Values measured by a sweep but recorded only in prose (``FINDINGS.md``,
    ``BENCHMARK_NOTES.md``) cannot be recomputed from a checkout, so they are transcribed once,
    by hand, each carrying the job ids and date that produced it. Transcribing them here rather
    than into the manuscript is what makes the provenance travel with the number.
    """
    return repo_root() / "paper" / "findings.toml"


def git_sha() -> str:
    """The checkout's sha, with a ``+dirty`` suffix when the tree has uncommitted changes.

    Matches the convention ``result.json`` and the Phoenix run span already use, so a figure
    and the run behind it can be lined up by string equality.
    """
    root = repo_root()
    sha = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
        capture_output=True, text=True, check=False,
    ).stdout.strip() or "unknown"
    dirty = subprocess.run(
        ["git", "-C", str(root), "status", "--porcelain"],
        capture_output=True, text=True, check=False,
    ).stdout.strip()
    return f"{sha}+dirty" if dirty else sha


def git_commit_date() -> str:
    """HEAD's commit date in UTC, or ``unknown`` without git metadata.

    The wall clock is not an input: rebuilding an unchanged checkout on a later day must
    not create a new manuscript diff. The Unix timestamp also avoids the committer's local
    timezone changing the date we report.
    """
    result = subprocess.run(
        ["git", "-C", str(repo_root()), "show", "-s", "--format=%ct", "HEAD"],
        capture_output=True, text=True, check=False,
    )
    if result.returncode or not result.stdout.strip():
        return "unknown"
    return datetime.fromtimestamp(int(result.stdout.strip()), UTC).date().isoformat()


def _count_rows(path: Path) -> int | None:
    if not path.is_file():
        return None
    lines = [ln for ln in path.read_text().splitlines() if ln.strip()]
    return max(len(lines) - 1, 0)


def read_roster() -> list[ExampleRow]:
    """Collect one row per PUBLISHED example.

    The synthetic scenarios are excluded: they simulate their own data from a withheld truth,
    which makes them a harness self-test rather than evidence about real biological data, and
    the paper reports only the published problems.

    ``reference.json`` is committed for all of them, so the bar is always readable. The PEtab
    tables are NOT: the benchmark examples are materialized by ``examples/setup.py`` and
    gitignored, so observable and condition counts are ``None`` in a fresh checkout. They are
    reported as such rather than guessed.
    """
    rows: list[ExampleRow] = []
    for name in BENCHMARK_EXAMPLES:
        problem = examples_root() / name / "problem"
        ref: dict[str, object] = {}
        ref_path = problem / "reference.json"
        if ref_path.is_file():
            ref = json.loads(ref_path.read_text())
        rows.append(ExampleRow(
            name=name,
            reference_k=ref.get("k"),
            reference_n=ref.get("n"),
            reference_nll=ref.get("nll"),
            n_observables=_count_rows(problem / "observables.tsv"),
            n_conditions=_count_rows(problem / "conditions.tsv"),
        ))
    return rows


def _cell(value: object) -> str:
    if value is None:
        return r"\needsmaterialize"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def render_roster(rows: list[ExampleRow]) -> str:
    """The roster longtable (Table 1)."""
    out = [
        DO_NOT_EDIT,
        r"% Columns marked \needsmaterialize require `python examples/setup.py` first.",
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r"Example & $k_\mathrm{ref}$ & $n$ & $\mathrm{nll}_\mathrm{ref}$ & Obs. & Cond. \\",
        r"\midrule",
    ]
    for r in rows:
        out.append(
            f"{r.name.replace('_', r'\_')} & {_cell(r.reference_k)} & "
            f"{_cell(r.reference_n)} & {_cell(r.reference_nll)} & "
            f"{_cell(r.n_observables)} & {_cell(r.n_conditions)} \\\\"
        )
    out += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(out)


def render_values(rows: list[ExampleRow], findings: dict[str, dict[str, object]]) -> str:
    """Every number the prose may cite, as a macro.

    Two sources, deliberately rendered into one file: counts derived from the checkout, and the
    curated sweep values. A reader of the manuscript cannot tell them apart, and should not have
    to -- both carry their provenance as a comment on the definition.
    """
    out = [DO_NOT_EDIT, "", "% -- derived from the checkout --"]
    out.append(rf"\newcommand{{\nExamples}}{{{len(rows)}}}")
    out.append("")
    out.append("% -- transcribed from sweep logs, see paper/findings.toml --")
    macros = {"nExamples", "repoSha", "generatedOn", "nUnmaterialized"}
    for key in sorted(findings):
        entry = findings[key]
        macro = entry.get("macro")
        if not isinstance(macro, str) or re.fullmatch(r"[A-Za-z]+", macro) is None:
            raise ValueError(f"{key}: macro must be an explicit name containing only ASCII letters")
        if macro in macros:
            raise ValueError(f"{key}: macro {macro!r} is already defined")
        macros.add(macro)
        out.append(f"% {entry.get('source', '?')} :: {entry.get('provenance', 'UNRECORDED')}")
        out.append(rf"\newcommand{{\{macro}}}{{{entry.get('value', '')}}}")
    out.append("")
    return "\n".join(out)


def render_provenance(rows: list[ExampleRow]) -> str:
    """What a reviewer needs to re-derive the generated half.

    ``generatedOn`` names HEAD's UTC commit date, not the time this renderer was run.
    """
    missing = [r.name for r in rows if r.n_observables is None]
    out = [
        DO_NOT_EDIT,
        "",
        rf"\newcommand{{\repoSha}}{{{git_sha()}}}",
        "% generatedOn is HEAD's commit date in UTC, not the generation time.",
        rf"\newcommand{{\generatedOn}}{{{git_commit_date()}}}",
        rf"\newcommand{{\nUnmaterialized}}{{{len(missing)}}}",
        "",
    ]
    if missing:
        out.append(f"% not materialized in this checkout: {', '.join(missing)}")
        out.append("")
    return "\n".join(out)


def build(out_dir: Path | None = None) -> dict[Path, str]:
    """Render every generated file and write it. Returns path to content, for the no-drift test."""
    target = out_dir or generated_dir()
    target.mkdir(parents=True, exist_ok=True)
    rows = read_roster()
    findings: dict[str, dict[str, object]] = {}
    if findings_path().is_file():
        findings = tomllib.loads(findings_path().read_text())
    files = {
        target / "roster.tex": render_roster(rows),
        target / "values.tex": render_values(rows, findings),
        target / "provenance.tex": render_provenance(rows),
    }
    for path, content in files.items():
        path.write_text(content)
    return files
